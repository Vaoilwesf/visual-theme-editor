// Селекторы сверены с разметкой SillyTavern (public/index.html, ветка
// release). Правила подбора:
//  - только классы, id и точное значение атрибута — браузер сверяет их
//    быстрее всего;
//  - никаких *, :has(), :nth-child и длинных цепочек предков: такие
//    селекторы перепроверяются при каждом изменении чата;
//  - не больше нескольких строк на шаблон — правило в CSS получается
//    короткое и почти ничего не весит;
//  - заголовки и прочее внутри сообщений отделены от интерфейса, чтобы
//    правка панелей не задевала текст в чате.
//
// У шаблона нет стилей — это только состав группы. Цвета, шрифты и
// прочее задаются потом через «Править группу».

